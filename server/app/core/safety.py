"""Medical safety guardrails, disclaimers, and emergency symptom detection."""

import re
from typing import List, Tuple

GENERAL_DISCLAIMER = (
    "Educational information only. AI Medical Assistant does not provide medical diagnosis, "
    "treatment, or prescriptions, and does not replace care from a qualified healthcare professional."
)

REPORT_DISCLAIMER = (
    "This AI-generated summary is for educational understanding only. It has not been clinically "
    "validated. Reference ranges vary by laboratory, age, sex, and clinical context. Always review "
    "your original medical report with a qualified healthcare professional."
)

IMAGE_DISCLAIMER = (
    "This image observation is generated by an AI vision model for educational reference only. "
    "The uploaded image has NOT been medically diagnosed or clinically validated. Always consult "
    "a qualified physician or specialist for evaluation of medical images or physical findings."
)

EMERGENCY_GUIDANCE = (
    "URGENT SAFETY NOTICE: Your description includes potential emergency warning signs. "
    "Please call your local emergency number (e.g., 911 in the US/Canada, 112 in the EU/India, "
    "999 in the UK) or go to the nearest emergency department immediately. Do not wait for an "
    "online tool to respond in an emergency."
)

EMERGENCY_PATTERNS: List[Tuple[str, str]] = [
    (r"\bchest\s+(pain|pressure|tightness|crushing|squeezing)\b", "Chest pain or pressure"),
    (r"\b(can't|cannot|unable\s+to|hard\s+to|difficulty)\s+breath(e|ing)\b|\bshortness\s+of\s+breath\b", "Difficulty breathing"),
    (r"\b(face\s+droop|facial\s+droop|slurred\s+speech|sudden\s+(weakness|numbness))\b", "Possible stroke warning signs"),
    (r"\b(suicid(e|al)|kill\s+myself|self[-\s]?harm|end\s+my\s+life|want\s+to\s+die)\b", "Mental health crisis / self-harm risk"),
    (r"\b(severe\s+bleeding|uncontrolled\s+bleeding|coughing\s+up\s+blood|vomiting\s+blood)\b", "Severe bleeding"),
    (r"\b(anaphylaxis|throat\s+swelling|tongue\s+swelling|swollen\s+throat|airway\s+closing)\b", "Severe allergic reaction / airway swelling"),
    (r"\b(unconscious|passed\s+out|fainted\s+and\s+not\s+waking|seizure|convulsion)\b", "Loss of consciousness or seizure"),
    (r"\b(overdose|poisoning|swallowed\s+poison)\b", "Potential poisoning or overdose"),
    (r"\bworst\s+headache\s+of\s+(my|their)\s+life\b|\bsudden\s+thunderclap\s+headache\b", "Sudden severe headache"),
]


def detect_emergency_signals(text: str) -> Tuple[bool, List[str]]:
    """Scan user input for emergency warning signs and return (is_emergency, matched_reasons)."""
    if not text:
        return False, []

    normalized = text.lower()
    reasons: List[str] = []
    for pattern, label in EMERGENCY_PATTERNS:
        if re.search(pattern, normalized):
            reasons.append(label)

    return len(reasons) > 0, reasons
